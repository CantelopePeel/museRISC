#!/usr/bin/env python3
"""Generate bare-metal TestFloat checker ELFs for the CVA6 model.

Reads Berkeley TestFloat `testfloat_gen` output (hex operand/result/
flags lines) and emits one RISC-V assembly checker per operation:
for each vector, load operands, clear fflags, execute the FPU op,
compare the result bits (canonicalizing NaNs: any NaN matches any
NaN) and the accrued exception flags exactly, then halt via HTIF
tohost like riscv-tests (odd pass value 1; fail value encodes the
case index). Vectors are embedded as data; large functions are
stride-sampled to at most --max-cases while preserving order.

Usage:
  testfloat_gen -level 1 -seed 1 f64_add | \\
    scripts/testfloat_cva6.py f64_add > f64_add.S
"""
import sys

OPS = {
    # name: (operands, asm instruction template, is_f32)
    "f32_add": (2, "fadd.s f3, f0, f1", True),
    "f32_sub": (2, "fsub.s f3, f0, f1", True),
    "f32_mul": (2, "fmul.s f3, f0, f1", True),
    "f32_div": (2, "fdiv.s f3, f0, f1", True),
    "f32_sqrt": (1, "fsqrt.s f3, f0", True),
    "f32_mulAdd": (3, "fmadd.s f3, f0, f1, f2", True),
    "f64_add": (2, "fadd.d f3, f0, f1", False),
    "f64_sub": (2, "fsub.d f3, f0, f1", False),
    "f64_mul": (2, "fmul.d f3, f0, f1", False),
    "f64_div": (2, "fdiv.d f3, f0, f1", False),
    "f64_sqrt": (1, "fsqrt.d f3, f0", False),
    "f64_mulAdd": (3, "fmadd.d f3, f0, f1, f2", False),
}

def main():
    if len(sys.argv) < 2 or sys.argv[1] not in OPS:
        print(f"usage: {sys.argv[0]} <op> [--max-cases N] < vectors.txt > out.S", file=sys.stderr)
        print("ops:", ", ".join(sorted(OPS)), file=sys.stderr)
        return 2
    op = sys.argv[1]
    max_cases = 0
    if "--max-cases" in sys.argv:
        max_cases = int(sys.argv[sys.argv.index("--max-cases") + 1])
    nops, inst, is32 = OPS[op]
    lines = [ln.split() for ln in sys.stdin if ln.strip() and not ln.startswith("+")]
    cases = []
    for parts in lines:
        assert len(parts) == nops + 2, (op, parts)
        cases.append(parts)
    total = len(cases)
    if max_cases and total > max_cases:
        stride = total / max_cases
        cases = [cases[int(i * stride)] for i in range(max_cases)]
    n = len(cases)
    w = sys.stdout.write
    w(f"# TestFloat checker: {op}, {n} of {total} level-1 cases (RNE, tininess-after)\n")
    w("# Generated by scripts/testfloat_cva6.py from Berkeley TestFloat vectors.\n")
    w("# Fail tohost code: result mismatch = case+2, flags mismatch = case+1000002.\n")
    w("""
    .section .text.init
    .globl _start
_start:
    la t0, trap_handler
    csrw mtvec, t0
    li t0, 0x2000
    csrs mstatus, t0
    csrwi frm, 0
    la s0, cases
    li s1, 0
    li s2, CASE_COUNT
loop:""")
    if is32:
        w("""
    flw f0, 0(s0)""")
        if nops >= 2:
            w("\n    flw f1, 8(s0)")
        if nops >= 3:
            w("\n    flw f2, 16(s0)")
        off_exp = 8 * nops
        w(f"""
    ld a3, {off_exp}(s0)
    ld a4, {off_exp + 8}(s0)
    csrwi fflags, 0
    {inst}
    fmv.x.w a0, f3
    frflags a1
    slli a0, a0, 32
    srli a0, a0, 32
    beq a0, a3, flags_ok
    li t0, 0x7F800000
    and t1, a0, t0
    and t2, a3, t0
    bne t1, t0, fail_result
    bne t2, t0, fail_result
    li t0, 0x007FFFFF
    and t1, a0, t0
    and t2, a3, t0
    beqz t1, fail_result
    beqz t2, fail_result
flags_ok:
    andi a1, a1, 0x1F
    bne a1, a4, fail_flags
""")
        stride = 8 * (nops + 2)
    else:
        w("""
    fld f0, 0(s0)""")
        if nops >= 2:
            w("\n    fld f1, 8(s0)")
        if nops >= 3:
            w("\n    fld f2, 16(s0)")
        off_exp = 8 * nops
        w(f"""
    ld a3, {off_exp}(s0)
    ld a4, {off_exp + 8}(s0)
    csrwi fflags, 0
    {inst}
    fmv.x.d a0, f3
    frflags a1
    beq a0, a3, flags_ok
    li t0, 0x7FF0000000000000
    and t1, a0, t0
    and t2, a3, t0
    bne t1, t0, fail_result
    bne t2, t0, fail_result
    li t0, 0x000FFFFFFFFFFFFF
    and t1, a0, t0
    and t2, a3, t0
    beqz t1, fail_result
    beqz t2, fail_result
flags_ok:
    andi a1, a1, 0x1F
    bne a1, a4, fail_flags
""")
        stride = 8 * (nops + 2)
    w(f"""    addi s0, s0, {stride}
    addi s1, s1, 1
    blt s1, s2, loop
    li a0, 1
    la t0, tohost
    sw a0, 0(t0)
1:  j 1b
fail_result:
    addi a0, s1, 2
    j fail_write
fail_flags:
    li a0, 1000002
    add a0, a0, s1
fail_write:
    slli a0, a0, 1
    ori a0, a0, 1
    la t0, tohost
    sw a0, 0(t0)
1:  j 1b
    .align 2
trap_handler:
    li a0, 3
    la t0, tohost
    sw a0, 0(t0)
1:  j 1b
    .data
    .globl tohost
    .align 6
tohost: .dword 0
    .globl fromhost
    .align 6
fromhost: .dword 0
    .align 3
cases:
""")
    for parts in cases:
        for p in parts[:-1]:
            w(f"    .dword 0x{int(p, 16):016X}\n")
        w(f"    .dword 0x{int(parts[-1], 16):X}\n")
    # CASE_COUNT define must precede use: emit via .equ at top is rewritten below
    return 0

if __name__ == "__main__":
    # Wrap main to inject CASE_COUNT: buffer output, prepend equ after gen.
    import io
    buf = io.StringIO()
    real = sys.stdout
    sys.stdout = buf
    rc = main()
    sys.stdout = real
    if rc == 0:
        text = buf.getvalue()
        n = text.count("    .dword 0x")
        # case count recomputed by caller contract: count lines is data-dependent; use marker
        # Simpler: CASE_COUNT derived from header line written by main (n of total).
        import re
        m = re.search(r": (\w+), (\d+) of (\d+)", text)
        cnt = m.group(2) if m else "0"
        real.write(f"    .equ CASE_COUNT, {cnt}\n")
        real.write(text)
    sys.exit(rc)
